// G-code export (from a machine program) and import (into a machine program).
import { finishProgram } from './vcarve.js';

const f3 = (v) => (Math.abs(v) < 5e-4 ? '0' : v.toFixed(3).replace(/\.?0+$/, ''));

export function exportGcode(P, m, meta = {}) {
  const out = [];
  out.push('(V-carve headstone program generated by CNC V-Bit Headstone Simulator)');
  if (meta.title) out.push(`(${meta.title.replace(/[()]/g, '')})`);
  out.push(`(Tool: ${meta.toolLabel || 'V-bit'})`);
  out.push(`(Stock: ${meta.stock || ''})`);
  out.push('(Origin: X0 Y0 = bottom-left of the stone face, Z0 = top of the face)');
  out.push(`(Estimated run time: ${formatTime(P.totalTime)})`);
  out.push('G21 G90 G17 G94');
  out.push(`G0 Z${f3(m.safeZ)}`);
  out.push(`M3 S${Math.round(m.rpm)}`);
  if (m.coolant) out.push('M8');
  out.push('G4 P2');
  let lastF = -1, lastMode = -1;
  let px = NaN, py = NaN, pz = NaN;
  for (let i = 1; i < P.n; i++) {
    const t = P.T[i];
    const x = P.X[i], y = P.Y[i], z = P.Z[i];
    let words = [];
    const mode = t === 0 ? 0 : 1;
    if (mode !== lastMode) { words.push(mode === 0 ? 'G0' : 'G1'); lastMode = mode; }
    if (f3(x) !== f3(px)) words.push('X' + f3(x));
    if (f3(y) !== f3(py)) words.push('Y' + f3(y));
    if (f3(z) !== f3(pz)) words.push('Z' + f3(z));
    if (words.length === 0 || (words.length === 1 && words[0][0] === 'G')) continue;
    if (mode === 1) {
      const F = t === 2 ? m.plunge : m.feed;
      if (F !== lastF) { words.push('F' + Math.round(F)); lastF = F; }
    }
    out.push(words.join(' '));
    px = x; py = y; pz = z;
  }
  out.push(`G0 Z${f3(m.safeZ)}`);
  if (m.coolant) out.push('M9');
  out.push('M5');
  out.push('M30');
  return out.join('\n') + '\n';
}

/**
 * Parse a subset of G-code: G0/G1/G2/G3, G17 arcs (I/J or R), G20/G21,
 * G90/G91, F words. Returns a machine program.
 */
export function parseGcode(text, m) {
  const X = [], Y = [], Z = [], T = [], F = [];
  let x = 0, y = 0, z = m.safeZ, feed = m.feed;
  let units = 1, abs = true, motion = 0;
  X.push(x); Y.push(y); Z.push(z); T.push(0); F.push(0);
  const push = (nx, ny, nz, t) => {
    X.push(nx); Y.push(ny); Z.push(nz);
    T.push(t === 0 ? 0 : (Math.abs(nx - x) < 1e-6 && Math.abs(ny - y) < 1e-6 && nz < z ? 2 : 1));
    F.push(t === 0 ? 0 : feed);
  };
  const lines = text.split(/\r?\n/);
  let count = 0;
  for (let raw of lines) {
    let line = raw.replace(/\(.*?\)/g, '').replace(/;.*$/, '').trim().toUpperCase();
    if (!line || line[0] === '%') continue;
    const words = {};
    const gs = [];
    for (const mm of line.matchAll(/([A-Z])\s*([-+]?\d*\.?\d+)/g)) {
      const L = mm[1], v = parseFloat(mm[2]);
      if (L === 'G') gs.push(v); else words[L] = v;
    }
    for (const g of gs) {
      if (g === 20) units = 25.4; else if (g === 21) units = 1;
      else if (g === 90) abs = true; else if (g === 91) abs = false;
      else if (g === 0 || g === 1 || g === 2 || g === 3) motion = g;
    }
    if (words.F !== undefined) feed = words.F * units;
    const has = words.X !== undefined || words.Y !== undefined || words.Z !== undefined;
    if (!has) continue;
    const tx = words.X !== undefined ? (abs ? words.X * units : x + words.X * units) : x;
    const ty = words.Y !== undefined ? (abs ? words.Y * units : y + words.Y * units) : y;
    const tz = words.Z !== undefined ? (abs ? words.Z * units : z + words.Z * units) : z;
    if (motion === 2 || motion === 3) {
      let cx, cy;
      if (words.R !== undefined) {
        const r = words.R * units;
        const dx = tx - x, dy = ty - y, d = Math.hypot(dx, dy);
        const h = Math.sqrt(Math.max(0, r * r - (d * d) / 4));
        const s = ((motion === 2) !== (r < 0)) ? -1 : 1;
        cx = x + dx / 2 - (s * h * dy) / d;
        cy = y + dy / 2 + (s * h * dx) / d;
      } else {
        cx = x + (words.I || 0) * units;
        cy = y + (words.J || 0) * units;
      }
      const r = Math.hypot(x - cx, y - cy);
      let a0 = Math.atan2(y - cy, x - cx), a1 = Math.atan2(ty - cy, tx - cx);
      if (motion === 2) { if (a1 >= a0 - 1e-9) a1 -= Math.PI * 2; }
      else if (a1 <= a0 + 1e-9) a1 += Math.PI * 2;
      const sweep = a1 - a0;
      const n = Math.max(2, Math.ceil((Math.abs(sweep) * r) / 0.5));
      const z0 = z;
      for (let s = 1; s <= n; s++) {
        const a = a0 + (sweep * s) / n;
        const nx = s === n ? tx : cx + r * Math.cos(a);
        const ny = s === n ? ty : cy + r * Math.sin(a);
        const nz = z0 + ((tz - z0) * s) / n;
        push(nx, ny, nz, 1);
        x = nx; y = ny; z = nz;
      }
    } else {
      push(tx, ty, tz, motion);
      x = tx; y = ty; z = tz;
    }
    count++;
  }
  if (count === 0) throw new Error('No motion commands found in file.');
  return finishProgram({ X, Y, Z, T, F }, m);
}

export function formatTime(sec) {
  if (!isFinite(sec)) return '—';
  sec = Math.round(sec);
  const h = Math.floor(sec / 3600), mnt = Math.floor((sec % 3600) / 60), s = sec % 60;
  return h ? `${h}h ${String(mnt).padStart(2, '0')}m` : `${mnt}m ${String(s).padStart(2, '0')}s`;
}
